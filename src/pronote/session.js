// -----------------------------------------------------------------------------
// The PRONOTE session: log in, stay logged in, log in again.
//
// PRONOTE has no public API; pawnote speaks the protocol of its web client
// (encrypted, compressed requests). This module is the only one that logs in,
// and it hands a ready session to the readers through `run()`.
//
// Three ways in, in this order:
//   1. the saved token (`/data/session.json`). PRONOTE gives one at every login,
//      bound to a device id we generate once and keep: it replaces the password
//      for the next login, the way the PRONOTE mobile app stays logged in. It
//      changes at every login, so it is saved again every time;
//   2. the username and password of the configuration. Each one is a new
//      "device" for PRONOTE, so it is only used when there is no usable token;
//   3. a QR code generated by PRONOTE (the "Log in with a QR code" action): the
//      way in for the accounts that log in through an ENT / CAS, which have no
//      PRONOTE password.
//
// A PRONOTE session expires after a while without requests. Rather than keep it
// alive with a request every two minutes, `run()` logs in again — with the
// token — when the server says the session is gone, and retries once.
// -----------------------------------------------------------------------------

import { randomUUID } from 'node:crypto';
import * as pawnote from 'pawnote';
import { createLogger } from '@gladysassistant/integration-sdk';
import { ACCOUNT_KINDS, hasCredentials } from '../config.js';
import { readJson, removeJson, writeJson } from '../storage.js';
import { NotConfiguredError, describeError, ERROR_CODES, isSessionLost } from './errors.js';

const logger = createLogger({ name: 'session' });

export const SESSION_FILE = 'session.json';

/** pawnote's account kinds (AccountKind), by the value of `account_kind`. */
export const PRONOTE_KINDS = { [ACCOUNT_KINDS.STUDENT]: 6, [ACCOUNT_KINDS.PARENT]: 7 };

/**
 * The address the user typed, as a comparable instance base: protocol added
 * when missing, no `eleve.html`, no query, no trailing slash, lower case.
 *
 * @param {string} url
 * @returns {string} `''` when it is not an address at all
 */
export function instanceBase(url) {
  const text = String(url ?? '').trim();
  if (!text) {
    return '';
  }
  try {
    const parsed = new URL(/^https?:\/\//i.test(text) ? text : `https://${text}`);
    const path = parsed.pathname.replace(/\/[^/]*\.html$/i, '').replace(/\/+$/, '');
    return `${parsed.protocol}//${parsed.host}${path}`.toLowerCase();
  } catch {
    return '';
  }
}

/**
 * Turn the text of a PRONOTE QR code into the object pawnote expects. The
 * code holds a small JSON (`{ "jeton": …, "login": …, "url": … }`); a phone
 * camera app shows it as text, and the user pastes it as is.
 *
 * @param {string} text
 */
export function parseQrContent(text) {
  let qr;
  try {
    qr = JSON.parse(String(text ?? '').trim());
  } catch {
    qr = null;
  }
  if (!qr || typeof qr.jeton !== 'string' || typeof qr.login !== 'string' || !qr.url) {
    const error = new Error('Not the content of a PRONOTE QR code');
    error.name = 'InvalidQrCodeError';
    throw error;
  }
  return qr;
}

export class PronoteSession {
  /**
   * @param {object} [options]
   * @param {object} [options.api] the pawnote module (a fake one in the tests)
   */
  constructor({ api = pawnote } = {}) {
    this.api = api;
    this.config = null;
    this.handle = null;
    this.pending = null;
    /** How the current handle was opened: 'token' | 'password' | 'qr'. */
    this.method = null;
  }

  /**
   * Take a new configuration. The open session is dropped when it no longer
   * matches the address, account kind or username.
   *
   * @param {ReturnType<import('../config.js').normalizeConfig>} config
   */
  setConfig(config) {
    const previous = this.config;
    this.config = config;
    if (
      previous &&
      (instanceBase(previous.url) !== instanceBase(config.url) ||
        previous.account_kind !== config.account_kind ||
        previous.username !== config.username ||
        previous.password !== config.password)
    ) {
      this.drop();
    }
  }

  /** Forget the open session (not the saved token). */
  drop() {
    this.handle = null;
    this.method = null;
  }

  /** Forget everything: the open session and the saved token. */
  async forget() {
    this.drop();
    const saved = await readJson(SESSION_FILE);
    // The device id stays: PRONOTE knows this Gladys under it.
    if (saved?.deviceUUID) {
      await writeJson(SESSION_FILE, { deviceUUID: saved.deviceUUID });
    } else {
      await removeJson(SESSION_FILE);
    }
  }

  /** Whether a token is saved, and which account it is for. */
  async savedAccount() {
    const saved = await readJson(SESSION_FILE);
    if (!saved?.token) {
      return null;
    }
    return { url: saved.url, username: saved.username, kind: saved.kind, origin: saved.origin };
  }

  /**
   * Run `fn` with a logged-in session; log in again and retry once when
   * PRONOTE says the session expired.
   *
   * @template T
   * @param {(handle: object, api: object) => Promise<T>} fn
   * @returns {Promise<T>}
   */
  async run(fn) {
    const handle = await this.open();
    try {
      return await fn(handle, this.api);
    } catch (err) {
      this.drop();
      if (!isSessionLost(err)) {
        throw err;
      }
      logger.info('PRONOTE session expired, logging in again');
      try {
        return await fn(await this.open(), this.api);
      } catch (retryError) {
        this.drop();
        throw retryError;
      }
    }
  }

  /** The logged-in handle, logging in when there is none. */
  async open() {
    if (this.handle) {
      return this.handle;
    }
    // One login at a time: the timer and an action may ask together.
    this.pending ??= this.login().finally(() => {
      this.pending = null;
    });
    return this.pending;
  }

  /**
   * Log in with the QR code PRONOTE shows (Mobile app → "Flash a QR code").
   *
   * @param {{ qr: string, pin: string }} fields
   */
  async loginWithQrCode({ qr, pin }) {
    const content = parseQrContent(qr);
    const saved = (await readJson(SESSION_FILE)) ?? {};
    const deviceUUID = saved.deviceUUID ?? randomUUID();
    const handle = this.api.createSessionHandle();
    const refresh = await this.api.loginQrCode(handle, {
      deviceUUID,
      pin: String(pin ?? '').trim(),
      qr: content,
      navigatorIdentifier: saved.navigatorIdentifier,
    });
    await this.save(refresh, deviceUUID, 'qr');
    this.handle = handle;
    this.method = 'qr';
    logger.info(`Logged in to PRONOTE with a QR code as ${refresh.username}`);
    return handle;
  }

  async login() {
    const config = this.config ?? {};
    const saved = (await readJson(SESSION_FILE)) ?? {};
    const deviceUUID = saved.deviceUUID ?? randomUUID();

    if (saved.token && this.matches(saved)) {
      try {
        const handle = this.api.createSessionHandle();
        const refresh = await this.api.loginToken(handle, {
          url: saved.url,
          kind: saved.kind,
          username: saved.username,
          token: saved.token,
          deviceUUID,
          navigatorIdentifier: saved.navigatorIdentifier,
        });
        await this.save(refresh, deviceUUID, saved.origin, saved.typedUsername);
        this.handle = handle;
        this.method = 'token';
        logger.debug(`Logged in to PRONOTE with the saved token as ${refresh.username}`);
        return handle;
      } catch (err) {
        if (describeError(err).code !== ERROR_CODES.BAD_CREDENTIALS) {
          throw err;
        }
        // A refused token is spent: forget it, and use the password if any.
        logger.warn('PRONOTE refused the saved token');
        await writeJson(SESSION_FILE, {
          deviceUUID,
          navigatorIdentifier: saved.navigatorIdentifier,
        });
      }
    }

    if (!hasCredentials(config)) {
      throw new NotConfiguredError();
    }
    const handle = this.api.createSessionHandle();
    const refresh = await this.api.loginCredentials(handle, {
      url: instanceBase(config.url),
      kind: PRONOTE_KINDS[config.account_kind],
      username: config.username,
      password: config.password,
      deviceUUID,
      navigatorIdentifier: saved.navigatorIdentifier,
    });
    await this.save(refresh, deviceUUID, 'password', config.username);
    this.handle = handle;
    this.method = 'password';
    logger.info(`Logged in to PRONOTE with the password as ${refresh.username}`);
    return handle;
  }

  /**
   * Whether a saved token belongs to the account of the configuration. An
   * empty address means "whatever the QR code logged into".
   */
  matches(saved) {
    const config = this.config ?? {};
    if (!config.url) {
      return true;
    }
    if (instanceBase(config.url) !== instanceBase(saved.url)) {
      return false;
    }
    if (saved.origin === 'qr') {
      return true;
    }
    return (
      saved.kind === PRONOTE_KINDS[config.account_kind] &&
      String(saved.typedUsername ?? '').toLowerCase() === config.username.toLowerCase()
    );
  }

  async save(refresh, deviceUUID, origin, typedUsername) {
    await writeJson(SESSION_FILE, {
      deviceUUID,
      url: refresh.url,
      kind: refresh.kind,
      username: refresh.username,
      token: refresh.token,
      navigatorIdentifier: refresh.navigatorIdentifier,
      origin,
      typedUsername,
      saved_at: new Date().toISOString(),
    });
  }
}
